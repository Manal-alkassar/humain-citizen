"""Exports the shared knowledge (policies, personas, phrasings, templates, guardrail rules) from the
Python package into web/engine/data.js, so the in-browser engine and the Python engine use ONE source.

    python scripts/build_web.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from humain import agent, gateway, guardrails, messages, nlu, policy  # noqa: E402

data = {
    "policy_kb": {"policies": policy.load_policies()},
    "personas": json.loads((ROOT / "humain/data/personas.json").read_text(encoding="utf-8"))["personas"],
    "templates": messages.T,
    "intents": nlu.INTENTS,
    "exemplars": nlu.EXEMPLARS,
    "concepts": nlu.CONCEPTS,
    "pairs": {k: list(v) for k, v in nlu.PAIRS.items()},
    "threshold": nlu.THRESHOLD,
    "time_patterns": [[p, l] for p, l in nlu._TIME_PATTERNS],
    "injection_patterns": guardrails.INJECTION_PATTERNS,
    "tool_schemas": guardrails.TOOL_SCHEMAS,
    "progressions": {k: [p, [[t, s] for t, s in prog]] for k, (p, prog) in gateway.PROGRESSIONS.items()},
    "rule_labels": {k: v[1] for k, v in policy.RULES.items()},
    "status_text": agent.STATUS_TEXT, "status_text_ar": agent.STATUS_TEXT_AR,
    "detail_ar": agent.DETAIL_AR, "value_ar": agent.VALUE_AR, "meaningful": sorted(agent.MEANINGFUL),
}
out = ROOT / "web/engine/data.js"
out.write_text("// GENERATED by scripts/build_web.py from the Python package. Do not edit by hand.\n"
               "var HUMAIN_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n"
               "if (typeof module !== 'undefined') module.exports = HUMAIN_DATA;\n", encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
